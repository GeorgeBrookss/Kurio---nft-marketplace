import { expect, login, test } from './fixtures'

test.describe('Perfil e carteiras', () => {
  test('edita perfil com validação e persiste após refresh @mobile', async ({ page }) => {
    await login(page)
    await page.goto('/perfil')
    const name = page.locator('#profile-displayName')
    await expect(name).toHaveValue('Ana Colecionadora')
    await name.fill('')
    await page.getByRole('button', { name: 'Salvar' }).first().click()
    await expect(page.getByText('Informe o nome de exibição')).toBeVisible()
    await page.locator('#profile-username').fill('bruno.nft')
    await name.fill('Ana C.')
    await page.getByRole('button', { name: 'Salvar' }).first().click()
    await expect(page.getByText('Nome de usuário em uso')).toBeVisible()
    await page.locator('#profile-username').fill('ana.c')
    await page.getByRole('button', { name: 'Salvar' }).first().click()
    await expect(page.getByText('Perfil salvo.')).toBeVisible()
    await page.reload()
    await expect(name).toHaveValue('Ana C.')
  })

  test('avatar e senha', async ({ page }) => {
    await login(page)
    await page.goto('/perfil')
    const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==', 'base64')
    await page.locator('#avatar-file').setInputFiles({ name: 'a.png', mimeType: 'image/png', buffer: png })
    await expect(page.getByRole('img', { name: 'Seu avatar' })).toBeVisible()

    await page.locator('#password-currentPassword').fill('errada')
    await page.locator('#password-newPassword').fill('NovaSenha1')
    await page.locator('#password-confirmPassword').fill('NovaSenha1')
    await page.getByRole('button', { name: 'Salvar' }).last().click()
    await expect(page.getByText('Senha atual incorreta').first()).toBeVisible()
    await page.locator('#password-currentPassword').fill('Kurio2026!')
    await page.getByRole('button', { name: 'Salvar' }).last().click()
    await expect(page.getByText('Senha alterada.')).toBeVisible()
  })

  test('carteiras principal e secundária com validação', async ({ page }) => {
    await login(page)
    await page.goto('/perfil/carteiras')
    await page.getByRole('button', { name: 'Editar' }).first().click()
    await page.locator('#wallet-primary-address').fill('0x123')
    await page.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(page.getByText('Use 0x seguido de 40 caracteres hexadecimais')).toBeVisible()
    await page.locator('#wallet-primary-address').fill('0xC0FFEE000000000000000000000000000000C0DE')
    await page.locator('#wallet-primary-network').selectOption('polygon')
    await page.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(page.getByText('Endereço já cadastrado nesta rede')).toBeVisible()
    await page.locator('#wallet-primary-address').fill('0x1111111111111111111111111111111111111111')
    await page.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(page.getByText('Carteira principal salva.')).toBeVisible()
    await page.reload()
    await expect(page.getByText('0x1111111111111111111111111111111111111111')).toBeVisible()
  })
})
